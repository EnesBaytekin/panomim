let lang = (() => {
  const saved = localStorage.getItem('panomim.lang');
  return saved === 'en' ? 'en' : 'tr';
})();

export function getLang() {
  return lang;
}

/** Translate a key with optional {var} interpolation. */
export function t(key, vars = {}) {
  const s = dict[lang][key] ?? dict.tr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}

export function toggleLang() {
  setLang(lang === 'tr' ? 'en' : 'tr');
}

export function setLang(l) {
  if (l !== 'tr' && l !== 'en') l = 'tr';
  localStorage.setItem('panomim.lang', l);
  document.documentElement.setAttribute('lang', l);
  // Language touches every rendered string; a reload is the reliable way to
  // apply it everywhere (login screen and app alike).
  location.reload();
}

// --- theme -------------------------------------------------------------------

export function initTheme() {
  const saved = localStorage.getItem('panomim.theme');
  const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  document.documentElement.setAttribute('data-theme', saved || (prefersDark ? 'dark' : 'light'));
}

export function currentTheme() {
  return document.documentElement.getAttribute('data-theme') || 'light';
}

export function setTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  localStorage.setItem('panomim.theme', theme);
  document.querySelectorAll('[data-theme-toggle]').forEach(b => {
    b.textContent = theme === 'light' ? '☾' : '☀';
  });
}

export function toggleTheme() {
  setTheme(currentTheme() === 'light' ? 'dark' : 'light');
}
